-- THROWAWAY DATABASES ONLY. Never run against production or staging.
--
-- Recreates the columns Story 2.2 reads, plus the owner-only tables the coach
-- must not see. plans, workouts, runs, and profiles are created by the web
-- repo, so a blank local Postgres has none of them. Policies match the
-- owner-only shape from the 2026-11-14 live read. This fixture does not widen
-- them, and the migration under test must not touch them.
--
-- Expects a supabase/postgres image (roles anon/authenticated, auth.users, auth.uid()).

begin;

do $$
begin
  if to_regclass('public.plans') is not null
     or to_regclass('public.workouts') is not null
     or to_regclass('public.runs') is not null
     or to_regclass('public.profiles') is not null
     or exists (select 1 from auth.users) then
    raise exception 'coach_read_fixture.sql refused: this database already has app tables or auth users. Run it only on a blank throwaway Postgres.';
  end if;
end $$;

create table public.profiles (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid references auth.users(id) on delete cascade,
  name text,
  updated_at timestamptz not null default now()
);

create table public.plans (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null,
  auth_user_id uuid references auth.users(id) on delete cascade,
  title text not null,
  start_date date not null,
  end_date date not null,
  is_active boolean not null default false,
  target_distance numeric,
  target_time integer
);

create table public.workouts (
  id uuid primary key default gen_random_uuid(),
  plan_id uuid not null references public.plans(id) on delete cascade,
  auth_user_id uuid references auth.users(id) on delete cascade,
  type text not null,
  distance numeric not null,
  duration integer,
  pace integer,
  notes text,
  completed boolean not null default false,
  completed_at timestamptz,
  actual_distance_km numeric,
  actual_duration_minutes integer,
  actual_pace integer,
  scheduled_date date not null
);

-- Production runs.id is bigint (live check 2026-11-14). pace is numeric here so
-- the RPC cast matches both integer and fractional stored paces.
create table public.runs (
  id bigint generated by default as identity primary key,
  auth_user_id uuid references auth.users(id),
  workout_id uuid references public.workouts(id) on delete set null,
  type text,
  distance numeric,
  duration integer,
  pace numeric,
  heart_rate integer,
  notes text,
  route jsonb,
  completed_at timestamptz,
  source_provider text,
  source_activity_id text,
  unique (source_provider, source_activity_id)
);

create table public.wellness_checkins (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  notes text
);

create table public.garmin_activities (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  summary text
);

create table public.run_debriefs (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  debrief text not null
);

create table public.conversations (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid not null references auth.users(id) on delete cascade,
  content text
);

alter table public.profiles enable row level security;
alter table public.plans enable row level security;
alter table public.workouts enable row level security;
alter table public.runs enable row level security;
alter table public.wellness_checkins enable row level security;
alter table public.garmin_activities enable row level security;
alter table public.run_debriefs enable row level security;
alter table public.conversations enable row level security;

grant select, insert, update, delete on public.profiles, public.plans, public.workouts, public.runs,
  public.wellness_checkins, public.garmin_activities, public.run_debriefs, public.conversations
  to authenticated;
grant usage, select on sequence public.runs_id_seq to authenticated;

create policy profiles_owner_access on public.profiles
  for all to authenticated
  using (auth_user_id = (select auth.uid()))
  with check (auth_user_id = (select auth.uid()));

create policy plans_owner_access on public.plans
  for all to authenticated
  using ((auth_user_id = (select auth.uid())) or (profile_id = (select auth.uid())))
  with check ((auth_user_id = (select auth.uid())) and (profile_id = (select auth.uid())));

create policy workouts_owner_access on public.workouts
  for all to authenticated
  using ((auth_user_id = (select auth.uid())) or exists (
    select 1 from public.plans p where p.id = workouts.plan_id
      and ((p.auth_user_id = (select auth.uid())) or (p.profile_id = (select auth.uid())))))
  with check ((auth_user_id = (select auth.uid())) and exists (
    select 1 from public.plans p where p.id = workouts.plan_id
      and ((p.auth_user_id = (select auth.uid())) or (p.profile_id = (select auth.uid())))));

create policy runs_select_own on public.runs for select to authenticated
  using (auth_user_id = (select auth.uid()));
create policy runs_insert_own on public.runs for insert to authenticated
  with check (auth_user_id = (select auth.uid()));
create policy runs_update_own on public.runs for update to authenticated
  using (auth_user_id = (select auth.uid()))
  with check (auth_user_id = (select auth.uid()));
create policy runs_delete_own on public.runs for delete to authenticated
  using (auth_user_id = (select auth.uid()));

create policy wellness_checkins_owner_access on public.wellness_checkins
  for all to authenticated
  using (auth_user_id = (select auth.uid()))
  with check (auth_user_id = (select auth.uid()));

create policy garmin_activities_owner_access on public.garmin_activities
  for all to authenticated
  using (auth_user_id = (select auth.uid()))
  with check (auth_user_id = (select auth.uid()));

create policy run_debriefs_owner_access on public.run_debriefs
  for all to authenticated
  using (auth_user_id = (select auth.uid()))
  with check (auth_user_id = (select auth.uid()));

create policy conversations_owner_access on public.conversations
  for all to authenticated
  using (auth_user_id = (select auth.uid()))
  with check (auth_user_id = (select auth.uid()));

commit;
