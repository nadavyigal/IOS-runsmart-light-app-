-- THROWAWAY DATABASES ONLY. Never run against production or staging.
--
-- Recreates the parts of the production schema that runs_workout_link.sql
-- exercises: plans, workouts and runs (only the columns the migration, the
-- policies and the test touch) with the production policies as listed on
-- 2026-11-14. These tables are created by the web repo's migrations, not this
-- repo's, so a bare local Postgres has none of them.
--
-- Expects a supabase/postgres image (roles anon/authenticated/service_role,
-- auth.users, auth.uid()).

-- One transaction so a failed guard aborts everything below, even when the
-- runner (e.g. psql without ON_ERROR_STOP) keeps going after an error.
begin;

do $$
begin
  if to_regclass('public.plans') is not null
     or to_regclass('public.workouts') is not null
     or to_regclass('public.runs') is not null
     or exists (select 1 from auth.users) then
    raise exception 'runs_workout_link_fixture.sql refused: this database already has app tables or auth users. Run it only on a blank throwaway Postgres.';
  end if;
end $$;

create table public.plans (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null,
  auth_user_id uuid references auth.users(id) on delete cascade,
  title text not null
);

create table public.workouts (
  id uuid primary key default gen_random_uuid(),
  plan_id uuid not null references public.plans(id) on delete cascade,
  auth_user_id uuid references auth.users(id) on delete cascade,
  completed boolean not null default false
);

-- Production shape: bigint id, nullable auth_user_id, unique (provider, activity).
create table public.runs (
  id bigint generated by default as identity primary key,
  auth_user_id uuid references auth.users(id),
  source_provider text,
  source_activity_id text,
  unique (source_provider, source_activity_id)
);

alter table public.plans enable row level security;
alter table public.workouts enable row level security;
alter table public.runs enable row level security;

grant all on public.plans, public.workouts, public.runs to anon, authenticated, service_role;

create policy plans_owner_access on public.plans
  for all to authenticated
  using ((auth_user_id = (select auth.uid())) or (profile_id = (select auth.uid())))
  with check ((auth_user_id = (select auth.uid())) and (profile_id = (select auth.uid())));

create policy workouts_owner_access on public.workouts
  for all to authenticated
  using ((auth_user_id = (select auth.uid())) or exists (
    select 1 from public.plans p where p.id = workouts.plan_id
      and ((p.auth_user_id = (select auth.uid())) or (p.profile_id = (select auth.uid())))))
  with check ((auth_user_id = (select auth.uid())) and exists (
    select 1 from public.plans p where p.id = workouts.plan_id
      and ((p.auth_user_id = (select auth.uid())) or (p.profile_id = (select auth.uid())))));

create policy runs_delete_own on public.runs for delete to authenticated using (auth_user_id = auth.uid());
create policy runs_insert_own on public.runs for insert to authenticated with check (auth_user_id = auth.uid());
create policy runs_select_own on public.runs for select to authenticated using (auth_user_id = auth.uid());
create policy runs_update_own on public.runs for update to authenticated
  using (auth_user_id = auth.uid()) with check (auth_user_id = auth.uid());

commit;
