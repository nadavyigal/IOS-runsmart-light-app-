-- Preserve the production view relation kind. GPS fixtures aren't required for
-- this baseline; optional Garmin route lookups return an empty result.
create view public.garmin_activity_points with (security_invoker = true) as
select auth_user_id, activity_id, 0::integer as sequence,
       null::double precision as latitude,
       null::double precision as longitude,
       null::timestamptz as "timestamp",
       null::double precision as horizontal_accuracy,
       null::double precision as altitude
from public.garmin_activities where false;

