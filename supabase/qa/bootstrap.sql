-- Local QA baseline only. The iOS migration tree extends a schema created in
-- the web repo. This fixture projects the pieces needed by the iOS client and
-- migration replay, using Running-coach- v0 migrations 001, 006,
-- 20260224123000, 20260224170000, and 20260504000000, with the iOS row models
-- and runs_workout_link_fixture.sql where production shapes differ (bigint IDs
-- for profiles/runs, UUID plan ownership). It is not a production schema dump.
-- The isolated runner opts in before replay. Never add this to migrations/.

do $$
begin
  if current_setting('runsmart.local_qa', true) is distinct from 'on'
     or to_regclass('public.runsmart_local_qa_marker') is not null
     or to_regclass('public.profiles') is not null
     or to_regclass('public.plans') is not null
     or to_regclass('public.workouts') is not null
     or to_regclass('public.runs') is not null
     or exists (select 1 from auth.users) then
    raise exception 'RunSmart QA bootstrap requires an opted-in, empty, disposable Supabase database';
  end if;
end $$;

-- Seed and test probes use this marker to refuse an unrelated database.
create table public.runsmart_local_qa_marker (id boolean primary key check (id));
insert into public.runsmart_local_qa_marker values (true);
alter table public.runsmart_local_qa_marker enable row level security;
revoke all on table public.runsmart_local_qa_marker from public, anon, authenticated;

