do $$
declare
  relation text;
begin
  foreach relation in array array[
    'profiles', 'challenge_enrollments', 'user_streaks', 'wellness_checkins',
    'garmin_connections', 'garmin_daily_metrics'
  ]
  loop
    execute format('alter table public.%I enable row level security', relation);
    execute format(
      'create policy local_qa_owner_access on public.%I for all to authenticated
       using (auth_user_id = (select auth.uid()))
       with check (auth_user_id = (select auth.uid()))', relation
    );
  end loop;
end $$;

